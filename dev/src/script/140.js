BF.settingsUI.updateLogBlock = function () {
  const books = BF.store.lsGetArray(BF.store.K.BOOKS_META, []);
  const daily = BF.store.lsGet(BF.store.K.DAILY, {});
  const hls = BF.store.lsGetArray(BF.store.K.HIGHLIGHTS, []);
  const bms = BF.store.lsGetArray(BF.store.K.BOOKMARKS, []);
  const vocab = BF.store.lsGetArray(BF.store.K.VOCAB, []);
  /* 版本号排序：数字段优先，preview/rc 等后缀排后 */
  const _verKey = function (v) {
    const m = String(v || '').match(/(\d+)\.(\d+)\.(\d+)/);
    if (!m) return [0, 0, 0, String(v || '')];
    return [parseInt(m[1], 10), parseInt(m[2], 10), parseInt(m[3], 10), String(v || '').replace(m[0], '')];
  };
  const log = (BF.settingsUI.UPDATE_LOG || []).slice().sort(function (a, b) {
    const ka = _verKey(a.ver), kb = _verKey(b.ver);
    for (let i = 0; i < 3; i++) if (ka[i] !== kb[i]) return kb[i] - ka[i];
    return ka[3] < kb[3] ? 1 : (ka[3] > kb[3] ? -1 : 0);
  });
  const rows = log.map(function (entry) {
    /* 快照模式（V2）：groups 域块优先渲染；旧 items 平铺继续兼容，两种可混用。
       note 是一条域块前的改版说明（只有快照条目带）。 */
    const li = function (s) { return '<li style="margin-bottom:4px">' + BF.dom.esc(s) + '</li>'; };
    let body = '';
    if (entry.note) body += '<div style="font-size:11.5px;color:var(--text-weak);margin:4px 0 6px">' + BF.dom.esc(entry.note) + '</div>';
    if (entry.groups) {
      body += entry.groups.map(function (g) {
        return '<div style="margin-bottom:8px">' +
          '<div style="font-weight:600;font-size:12px;color:var(--text-dim);margin-bottom:2px">' + BF.dom.esc(g.name) + '</div>' +
          '<ul style="margin:2px 0 0 18px;padding:0;font-size:12px;line-height:1.7;color:var(--text-dim)">' + (g.items || []).map(li).join('') + '</ul>' +
        '</div>';
      }).join('');
    } else {
      body += '<ul style="margin:6px 0 0 18px;padding:0;font-size:12px;line-height:1.7;color:var(--text-dim)">' + (entry.items || []).map(li).join('') + '</ul>';
    }
    return '<div style="margin-bottom:12px">' +
      '<div style="font-weight:600;color:var(--accent-ink);font-size:13px">' + BF.dom.esc(entry.ver) +
        (entry.date ? ' <span style="color:var(--text-weak);font-weight:400;font-size:11px">' + BF.dom.esc(entry.date) + '</span>' : '') +
      '</div>' +
      body +
    '</div>';
  }).join('');
  /* 数据现状并入最新版本条目下 */
  const snap = BF.dom.esc('数据现状：书籍 ' + books.length + ' 本 / 划线 ' + hls.length + ' / 书签 ' + bms.length + ' / 生词 ' + vocab.length + ' / 阅读 ' + Object.keys(daily).length + ' 天');
  return rows + '<div style="border-top:1px solid var(--border);margin-top:10px;padding-top:8px;font-size:11px;color:var(--text-weak)">' + snap + '</div>';
};

