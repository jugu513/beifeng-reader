/* ================= 18.6 BF.agent · 代理内核 =================
   与既有地基的关系（破例即多真源，所以逐条写死在这里）：
   - 不新建写通道：写动作只经 BF.act.run；回滚只经 BF.undo 那条栈。
     内核自己不调用撤销闭包——那样全局栈里还留着同一条记录，之后一次
     Ctrl+Z 会把同一个逆操作重放第二遍。
   - 不登记空 undo：空 undo 会让「什么都没撤销」被记成撤销成功。
     没有真实逆操作的动作一律拒绝执行，等记录级版本（前置检查）落地再开。
   - 不运行时注册进 BF.hub：能力面只读自 BF.hub.describe()。
   - 不自建权限判定：域与四级权限同名同序，开票只能落在当前级别已覆盖的
     集合内；内核永远不提级，覆盖不到就拒绝并说明去哪里设。
   - 动作入口在 DSL 终端，不另开 GUI 面板（结构红线：不加浮动窗元素）。 */
